type FieldIn = NonNullable<In['studios'][number]['inputs']>[number];
function opt(value: string, label: LT) {
  return { value, label };
}
function field(
  id: string,
  type: FieldIn['type'],
  label: LT,
  required: boolean,
  options: { value: string; label: LT }[] = [],
  min?: number,
  max?: number,
  def?: string | number | boolean,
): FieldIn {
  return {
    id,
    type,
    label,
    required,
    options,
    ...(min === undefined ? {} : { min }),
    ...(max === undefined ? {} : { max }),
    ...(def === undefined ? {} : { default: def }),
  };
}
function studio(
  id: string,
  name: LT,
  output: 'text' | 'audio' | 'image' | 'video' | 'captions' | 'pack',
  costId: string,
  requires: string[],
  order: number,
  inputs: FieldIn[],
  workload: { textField?: string; countField?: string; units?: number },
  extra: Partial<In['studios'][number]> = {},
): In['studios'][number] {
  return {
    id,
    name,
    role: `studio-${id}`,
    output,
    costId,
    requires,
    order,
    inputs: inputs.map((f, i) => ({ ...f, order: i + 1 })),
    workload,
    ...extra,
  };
}
