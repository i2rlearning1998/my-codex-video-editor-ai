export type AiKey = keyof typeof S;
export function t(
  key: AiKey,
  vars: Record<string, string | number> = {},
): string {
  const pair = S[key];
  const text = getLanguage() === 'hi' ? pair[1] : pair[0];
  return text.replace(/\{(\w+)\}/g, (_, k: string) =>
    k in vars ? String(vars[k]) : `{${k}}`,
  );
}
