// P2-R2 (P2B-18): `npm run docs:capability-sheet` writes
// docs/CAPABILITY-SHEET.md from the code (src/director/capabilities.ts), the
// same text the planning model reads, so it never drifts.
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { createServer } from 'vite';

const root = fileURLToPath(new URL('../', import.meta.url));
const server = await createServer({
  root,
  configFile: false,
  logLevel: 'silent',
  server: { middlewareMode: true, watch: null, hmr: false },
});
try {
  const m = await server.ssrLoadModule('/src/director/capabilities.ts');
  const { text, version } = m.capabilitySheet();
  await writeFile(
    new URL('../docs/CAPABILITY-SHEET.md', import.meta.url),
    `# Director capability sheet\n\nGenerated by \`npm run docs:capability-sheet\` from the editor's code (src/director/capabilities.ts). Do not edit by hand. The planning model reads exactly this text (version \`${version}\`); see docs/video-plan.md for the full plan format and docs/GRAPHICS-BLOCKS.md for the blocks.\n\n\`\`\`text\n${text}\n\`\`\`\n`,
  );
  console.log(`docs/CAPABILITY-SHEET.md written (version ${version}).`);
} finally {
  await server.close();
}
