// P2-R2 (P2B-18): `npm run docs:capability-sheet` writes
// docs/CAPABILITY-SHEET.md from the code (src/director/capabilities.ts), the
// same text the planning model reads, so it never drifts.
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { createServer } from 'vite';

const root = fileURLToPath(new URL('../', import.meta.url));
const server = await createServer({
  root,
  configFile: false,
  logLevel: 'silent',
  server: { middlewareMode: true, watch: null, hmr: false },
});
try {
  const m = await server.ssrLoadModule('/src/director/capabilities.ts');
  const { text, version } = m.capabilitySheet();
  // ROUND-C1: the live part (providers by kind, web rules, video types, the
  // Project kit) comes from the Platform Config at run time; the docs show
  // it for the default config.
  const live = await server.ssrLoadModule('/src/tools/capabilities.ts');
  const cfg = await server.ssrLoadModule('/src/platform-config/index.ts');
  const config = cfg.platformConfigSchema.parse(cfg.defaultConfig());
  const lines = live.liveSheetLines(config, {}).join('\n');
  await writeFile(
    new URL('../docs/CAPABILITY-SHEET.md', import.meta.url),
    `# Director capability sheet\n\nGenerated by \`npm run docs:capability-sheet\` from the editor's code (src/director/capabilities.ts). Do not edit by hand. The planning model reads exactly this text (version \`${version}\`); see docs/video-plan.md for the full plan format and docs/GRAPHICS-BLOCKS.md for the blocks.\n\n\`\`\`text\n${text}\n\`\`\`\n\n## Live part (capability sheet v2)\n\nAt run time the planner reads the text above followed by lines made from the live Platform Config and the Project (src/tools/capabilities.ts; its version is a hash of the whole). For the default config they are:\n\n\`\`\`text\n${lines}\n\`\`\`\n`,
  );
  // ROUND-C3 (4.2): the capability matrix, from src/director/capability-matrix.ts.
  const mx = await server.ssrLoadModule('/src/director/capability-matrix.ts');
  const cell = (xs) => xs.map((x) => `\`${x}\``).join(', ') || '—';
  await writeFile(
    new URL('../docs/CAPABILITY-MATRIX.md', import.meta.url),
    `# Capability matrix\n\nGenerated by \`npm run docs:capability-sheet\` from src/director/capability-matrix.ts. Do not edit by hand. Every editor command family and every Video Plan v4 field, with the way Claude reaches it through the connector; tests/round-c3/capability-matrix.test.ts fails when a command or a plan field has no row (AGENTS.md section 3).\n\n| Family | Editor commands | Plan fields | Claude's way |\n| --- | --- | --- | --- |\n${mx.CAPABILITY_MATRIX.map(
      (r) =>
        `| ${r.family} | ${cell(r.commands)} | ${cell(r.plan)} | ${r.internal ? `Editor only: ${r.internal}` : cell(r.mcp)} |`,
    ).join('\n')}\n`,
  );
  console.log(`docs/CAPABILITY-SHEET.md written (version ${version}).`);
} finally {
  await server.close();
}
