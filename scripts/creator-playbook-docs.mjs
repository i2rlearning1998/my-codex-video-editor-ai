// ROUND-C2 (2.5): docs/creator-playbook/01 to 06 are written from the
// config defaults (src/platform-config/texts), so the repo docs and the
// config never drift. `npm run docs:playbook`; a test checks they match.
import { readFileSync, writeFileSync } from 'node:fs';

export const CHAPTERS = [
  ['01-audience-and-goal', 'Audience and goal'],
  ['02-story-and-script', 'Story and script'],
  ['03-look-and-feel', 'Look and feel'],
  ['04-media-and-sound', 'Media and sound'],
  ['05-camera-and-motion', 'Camera and motion'],
  ['06-review-and-publish', 'Review and publish'],
];
/** The chapter text as the TS file holds it (a JSON string literal). */
export function chapterText(id) {
  const src = readFileSync(
    `src/platform-config/texts/creator-playbook-${id}.ts`,
    'utf8',
  );
  const m = /=\s*((['"])(?:\\.|(?!\2)[^\\])*\2)\s*as const;/s.exec(src);
  if (!m) throw new Error(`No text in creator-playbook-${id}.ts`);
  // The file is the repo's own string literal (single or double quotes).
  return new Function(`return ${m[1]};`)();
}
export function chapterDoc(id, title) {
  return `# ${id.slice(0, 2)} ${title}\n\n<!-- Generated by npm run docs:playbook from src/platform-config/texts/creator-playbook-${id}.ts (the config default the owner edits in Admin). Do not edit by hand. -->\n\n${chapterText(id)}\n`;
}
if (process.argv[1]?.endsWith('creator-playbook-docs.mjs'))
  for (const [id, title] of CHAPTERS)
    writeFileSync(`docs/creator-playbook/${id}.md`, chapterDoc(id, title));
