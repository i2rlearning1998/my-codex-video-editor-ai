// FINAL3 V5.2: `npm run docs:plan-cheatsheet` writes
// docs/creator-playbook/07-plan-cheatsheet.md from the code's registries
// (the Video Plan v2 schema lists, the starter kit, camera controllers and
// easings, caption styles, transitions), so the cheatsheet never drifts.
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { createServer } from 'vite';

const root = fileURLToPath(new URL('../', import.meta.url));
const server = await createServer({
  root,
  configFile: false,
  logLevel: 'silent',
  server: { middlewareMode: true, watch: null, hmr: false },
});
try {
  const plan = await server.ssrLoadModule('/src/video-plan/index.ts');
  const camera = await server.ssrLoadModule('/src/ai-spec/camera-names.ts');
  const list = (values) => values.map((value) => `\`${value}\``).join(', ');
  const text = `# 07 Plan cheatsheet

Generated by \`npm run docs:plan-cheatsheet\` from the editor's code. Do not edit by hand.

A Video Plan starts with \`"format": "${plan.PLAN_FORMAT}"\` and \`"version": ${plan.PLAN_VERSION}\` (version 2 plans still read). The full format is in docs/video-plan.md.

## Limits

| What | Limit |
| --- | --- |
| Scenes | ${plan.PLAN_LIMITS.scenes} |
| Layers per scene | ${plan.PLAN_LIMITS.layers} |
| Overlays | ${plan.PLAN_LIMITS.overlays} |
| Poses per media layer | ${plan.PLAN_LIMITS.poses} |
| Narration per scene | ${plan.PLAN_LIMITS.narration} characters |
| Text per layer | ${plan.PLAN_LIMITS.text} characters |
| Whole video | ${plan.PLAN_LIMITS.duration} s |

## Values

| Field | Allowed values |
| --- | --- |
| \`meta.aspect\` | ${list(plan.PLAN_ASPECTS)} |
| \`meta.build\` | ${list(plan.PLAN_BUILDS)} |
| \`layer.kind\` | ${list(plan.PLAN_LAYER_KINDS)} |
| \`layer.anchor\` | ${list(plan.PLAN_ANCHORS)} |
| \`layer.size\` | ${list(plan.PLAN_SIZES)} |
| \`layer.enter\`, \`layer.exit\` | ${list(plan.PLAN_ENTERS)} |
| \`layer.shape\` | ${list(plan.PLAN_SHAPES)} |
| \`layer.dash\` | ${list(plan.PLAN_DASHES)} |
| \`layer.loop\` | ${list(plan.PLAN_LOOPS)} |
| \`layer.bubble\` | ${list(plan.PLAN_BUBBLES)} |
| \`layer.tail\` | ${list(plan.PLAN_TAILS)} |
| \`mediaIntent.type\` | ${list(plan.PLAN_MEDIA_TYPES)} |
| \`feel.cameraTendency\` | ${list(plan.PLAN_TENDENCIES)} |
| \`feel.pacing\` | ${list(plan.PLAN_PACING)} |
| \`feel.captionStyle\`, \`captions.style\` | ${list(plan.KIT_CAPTION_STYLES)} |
| \`feel.transition\`, \`transitionOut.type\` | ${list(plan.KIT_TRANSITIONS)} |
| \`camera.controller\` | ${list(camera.CONTROLLERS)} |
| \`camera.easing\` | ${list(camera.CAMERA_EASINGS)} |

## Version 3: one timeline, exact places, diagrams

- \`meta.build: "timeline"\` builds the whole video as ONE scene (one timeline): each plan scene is a chapter (its \`durationHint\`, narration and layers, with layer times relative to the chapter). Without it (\`"scenes"\`) each plan scene is its own scene.
- \`overlays[]\` are layers shown over the whole video (a logo, a title tag): same fields as a layer; in \`"scenes"\` mode they are repeated on every scene. The same picture used many times is added once.
- \`narrationTrack: { "query": "<file name>", "volume", "start" }\` is one narration file under the whole video (found by name in Media). The video lasts at least as long.
- Exact place: \`at: {x, y}\` is the layer's centre in percent of the canvas; \`width\` and \`height\` are percent of the canvas; \`rotation\` (degrees), \`opacity\` (0 to 1).
- Movement: \`move: { to: {x, y}, start, duration, easing }\` slides the centre; \`loop\` keeps a layer alive (\`float\`, \`pulse\`, \`wiggle\`, \`spin\`); \`poses: [{ query, start }]\` on a media layer swaps the picture at those times (a talking and a pointing pose); \`cameras: [...]\` on a scene are several shots, each with \`start\` and \`duration\`.
- Media edge: \`feather\` (px on a 1080 canvas) and \`featherEdge\` (\`all\`, \`top\`, \`bottom\`, \`left\`, \`right\`) fade the edge of a picture into what is below.
- Text look: \`color\`, \`fontSize\` (px on a 1080 canvas), \`weight\` (100 to 900), \`highlight\` (a coloured box behind the text) or \`outline\`.
- \`"kind": "shape"\`: \`rectangle\` and \`ellipse\` (\`color\` fills; \`stroke\` alone is an outline), \`line\` and \`arrow\` (\`from\`, \`to\`, \`stroke\`, \`strokeWidth\`, \`dash\`, \`arrowStart\`), \`arc\` (\`at\` centre, \`radius\` in percent of the short side, \`startAngle\`, \`endAngle\`: 0 is right, angles run clockwise) and \`protractor\` (\`at\` the middle of its base line, \`radius\`). \`"enter": "wipe"\` draws a line, arrow or arc on from left to right.
- \`"kind": "bubble"\`: a speech or thought bubble around \`text\` (\`bubble\`: \`speech\`, \`thought\`; \`tail\`: \`left\`, \`right\`, \`none\`; \`color\` fill, \`stroke\` outline).

## Starter kit (\`"kind": "kit"\`, \`"kit": "<id>"\`)

Items: ${list(plan.KIT_ITEMS)}.

Backgrounds: ${list(plan.KIT_BACKGROUNDS)}.

A kit layer's \`text\` may hold two lines separated by \`|\` (name|role, title|subtitle, number|label, quote|author).
`;
  const target = new URL(
    '../docs/creator-playbook/07-plan-cheatsheet.md',
    import.meta.url,
  );
  // Written as the repository's formatter writes it, so format:check passes.
  const prettier = await import('prettier');
  const options = (await prettier.resolveConfig(fileURLToPath(target))) ?? {};
  await writeFile(
    target,
    await prettier.format(text, { ...options, parser: 'markdown' }),
  );
  console.log('Wrote docs/creator-playbook/07-plan-cheatsheet.md');
} finally {
  await server.close();
}
